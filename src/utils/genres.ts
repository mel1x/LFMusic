/** Readable genre name for the current language; unknown tags keep their own spelling. */
export function genreDisplayName(genre: string, language: string): string {
  const known = GENRE_NAMES[genre.trim().toLowerCase()]
  if (known) return language === 'en' ? known[1] : known[0]
  const cleaned = genre.trim().replace(/genre$/i, '').replace(/[_-]+/g, ' ').trim() || genre.trim()
  return cleaned.charAt(0).toUpperCase() + cleaned.slice(1)
}
